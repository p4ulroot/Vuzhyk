def _append_docx(master, src_path):
    """Добавляет содержимое другого .docx в master (без sectPr)."""
    src = Document(src_path)
    master.add_page_break()
    body = master.element.body
    for child in src.element.body:
        if child.tag == qn("w:sectPr"):
            continue
        body.append(deepcopy(child))


def build_combined(part_paths):
    """Один файл: отчёт + тест-план + чек-лист + тест-кейсы."""
    # Порядок: титульный отчёт, затем приложения с документацией
    ordered = []
    by_name = {os.path.basename(p): p for p in part_paths}
    for name in ("Otchet_Lab1.docx", "01_Test_Plan.docx", "02_Check_List.docx", "03_Test_Cases.docx"):
        if name in by_name:
            ordered.append(by_name[name])
    if not ordered:
        ordered = list(part_paths)

    master = Document(ordered[0])
    for path in ordered[1:]:
        _append_docx(master, path)

    out = os.path.join(HERE, "04_Lab1_Combined.docx")
    master.save(out)
    return out


